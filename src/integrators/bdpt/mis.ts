/**
 * multiple importance sampling (MIS) across BDPT's strategies
 *
 * a full path x₀ … xₙ₋₁ (x₀ on a light, xₙ₋₁ the camera) can be produced by every strategy s:
 * the first s vertices traced from the light, the rest from the camera, joined between xₛ₋₁ and xₛ.
 * Each strategy has its own probability density pₛ for the same path; the weight of strategy s is
 *
 *     wₛ = h(pₛ) / Σᵢ h(pᵢ)     - h(p) = p (balance), p² (power) or 1 for each valid strategy (uniform)
 *
 * The densities only differ in which side generated each vertex, so neighbouring strategies relate
 * by a single ratio, e.g. pₛ₊₁ / pₛ = (density of xₛ from the light) / (density of xₛ from the camera).
 * Walking those ratios outwards from s gives Σᵢ h(pᵢ / pₛ) without ever computing a full pₛ.
 */

export type MisHeuristic = 'balance' | 'power' | 'uniform'

/** one vertex of the full path, as MIS sees it */
export interface MisVertex {
  /** density (per area) of this vertex when generated by tracing from the light side */
  pdfFromLight: number
  /** density (per area) of this vertex when generated by tracing from the camera side */
  pdfFromCamera: number
  /** a delta BSDF here - no strategy can connect to this vertex */
  isDelta: boolean
}

/**
 * weight of strategy `s` for the full path `vertices` (light end first, camera last)
 */
export function misWeight(
  vertices: readonly MisVertex[],
  s: number,
  heuristic: MisHeuristic,
): number {
  const n = vertices.length
  let sumOfRatios = 0

  // strategies with more light vertices: s + 1, s + 2, ...
  let ratio = 1
  for (let other = s + 1; other < n; other++) {
    const vertex = vertices[other - 1] // switches from camera side to light side
    ratio *= orNonZero(vertex.pdfFromLight) / orNonZero(vertex.pdfFromCamera)
    if (isUsable(vertices, other)) sumOfRatios += remap(ratio, heuristic)
  }

  // strategies with fewer light vertices: s - 1, s - 2, ... 0
  ratio = 1
  for (let other = s - 1; other >= 0; other--) {
    const vertex = vertices[other] // switches from light side to camera side
    ratio *= orNonZero(vertex.pdfFromCamera) / orNonZero(vertex.pdfFromLight)
    if (isUsable(vertices, other)) sumOfRatios += remap(ratio, heuristic)
  }

  return 1 / (1 + sumOfRatios)
}

/**
 * can strategy `s` (joining x_(s-1) and x_(s)) produce this path at all?
 *
 * - not when either end of the connection is delta - nothing can connect to a perfect mirror
 * - not s = n: a light path can't hit a pinhole camera
 * - not (s, t) = (1, 1): a light point connected straight to the camera - never evaluated, the
 *   camera seeing a light is s = 0's job (as in PBRT)
 */
function isUsable(vertices: readonly MisVertex[], s: number): boolean {
  const n = vertices.length
  const t = n - s
  if (t < 1 || (s === 1 && t === 1)) return false
  const lightEndIsDelta = s > 0 && vertices[s - 1].isDelta
  return !lightEndIsDelta && !vertices[s].isDelta
}

function remap(ratio: number, heuristic: MisHeuristic): number {
  switch (heuristic) {
    case 'balance':
      return ratio
    case 'power':
      return ratio * ratio
    case 'uniform':
      return 1
  }
}

/** delta vertices have zero pdfs - they're excluded by `isDelta`, this just keeps the ratios finite */
function orNonZero(pdf: number): number {
  return pdf === 0 ? 1 : pdf
}
